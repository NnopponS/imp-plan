import {expect,test} from '@playwright/test'
import {startMatch} from './start-match'

test.use({viewport:{width:320,height:690},hasTouch:true,isMobile:true})
test('the assay ledger keeps one compact token tray and flags duplicate weight assignments',async({page})=>{
 await page.goto('./season/1/')
 await page.getByRole('button',{name:'Practice Scale Game',exact:true}).click()
 await startMatch(page)
 const bench=page.getByRole('region',{name:'Scale Game bench'})
 const details=bench.getByText('Lock one team answer',{exact:true})
 const ledger=bench.getByRole('group',{name:'Choose a mineral'})
 const submit=bench.getByRole('button',{name:'Submit final weights'})
 await expect(ledger).toBeHidden()
 expect((await details.boundingBox())!.height).toBeGreaterThanOrEqual(44)
 await details.tap()
 await expect(ledger).toBeVisible()
 await expect(ledger.getByRole('button',{name:/Brass/})).toHaveCount(0)
 await expect(ledger.getByText('Reference',{exact:true})).toBeVisible()
 await expect(bench.locator('select')).toHaveCount(0)
 const menu=(await bench.getByText(/Possible weights:/).innerText()).split('Possible weights: ')[1].match(/\d+/g)!.map(Number)
 const jade=ledger.getByRole('button',{name:'Assign Jade weight'})
 const quartz=ledger.getByRole('button',{name:'Assign Quartz weight'})
 await expect(jade).toHaveAttribute('aria-pressed','true')
 const values=(mineral:string)=>bench.getByRole('group',{name:'Weight tokens for '+mineral})
 const token=(mineral:string,value:number)=>values(mineral).getByRole('button',{name:value+' units',exact:true})
 expect((await jade.boundingBox())!.height).toBeGreaterThanOrEqual(44)
 expect((await token('Jade',menu[0]).boundingBox())!.height).toBeGreaterThanOrEqual(44)
 await token('Jade',menu[0]).tap()
 await expect(token('Jade',menu[0])).toHaveAttribute('aria-pressed','true')
 await quartz.press('Enter')
 await expect(quartz).toHaveAttribute('aria-pressed','true')
 await expect(values('Jade')).toHaveCount(0)
 await expect(values('Quartz').getByRole('button')).toHaveCount(menu.length)
 await token('Quartz',menu[0]).press('Enter')
 await expect(bench.getByText('Use a different weight for each mineral.')).toBeVisible()
 await expect(jade).toHaveAttribute('data-duplicate','true')
 await expect(quartz).toHaveAttribute('data-duplicate','true')
 await expect(submit).toBeDisabled()
 await token('Quartz',menu[1]).tap()
 await expect(bench.getByText('Use a different weight for each mineral.')).toHaveCount(0)
 await bench.getByRole('button',{name:'Clear Quartz weight'}).press('Enter')
 await expect(quartz).not.toHaveAttribute('data-assigned')
 await expect(submit).toBeDisabled()
 await details.tap()
 await expect(ledger).toBeHidden()
 await details.tap()
 await expect(jade).toHaveAttribute('data-assigned',String(menu[0]))
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(320)
})
