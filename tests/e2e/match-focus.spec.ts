import {expect,test,type Page} from '@playwright/test'
import {startMatch} from './start-match'

const presence=(p:Page)=>p.getByRole('region',{name:'At this table',exact:true})
const focus=(p:Page)=>p.getByRole('button',{name:'Board focus',exact:true})
const exit=(p:Page)=>p.getByRole('button',{name:'Exit focus',exact:true})
const board=(p:Page)=>p.getByLabel('Blind Gomoku board',{exact:true})
const cell=(p:Page,r:number,c:number,state='open')=>board(p).getByRole('button',{name:`Row ${r}, column ${c}, ${state}`,exact:true})
const fit=(p:Page)=>p.evaluate(()=>document.documentElement.scrollWidth===innerWidth)
const capture=async(p:Page,name:string)=>{if(process.env.CAPTURE_MATCH_FOCUS==='1')await p.screenshot({path:`../.imp-match-focus-proof/match-focus-${name}.png`,animations:'disabled'})}

test('320px gives real seats and larger table, with playable touch focus that can be exited',async({browser,baseURL})=>{
 const ctx=await browser.newContext({viewport:{width:320,height:710},hasTouch:true,isMobile:true,reducedMotion:'reduce'})
 try{
  const page=await ctx.newPage();await page.goto(baseURL!)
  await page.getByRole('button',{name:'Practice Blind Gomoku',exact:true}).tap()
  await startMatch(page)
  await expect(presence(page)).toBeInViewport()
  await expect(presence(page).getByText('Player',{exact:true})).toBeVisible()
  await expect(presence(page).getByText('Bot 1',{exact:true})).toBeVisible()
  await expect(presence(page).locator('[data-player-look]')).toHaveCount(2)
  await expect(page.locator('.room .roster')).not.toBeVisible()
  const before=await board(page).boundingBox()
  await capture(page,'phone-normal')
  await focus(page).tap()
  await expect(exit(page)).toHaveAttribute('aria-pressed','true')
  await expect(exit(page)).toBeInViewport()
  await expect(presence(page)).not.toBeVisible()
  await expect(page.getByRole('heading',{name:'Your turn',exact:true})).toBeVisible()
  await expect(page.getByRole('group',{name:'Stone covers'})).toBeVisible()
  const focused=await board(page).boundingBox()
  expect(focused!.y).toBeLessThan(before!.y-24)
  expect(focused!.width).toBeGreaterThan(280)
  await capture(page,'phone-focus')
  await cell(page,8,8).tap()
  await expect(cell(page,8,8,'veiled')).toBeVisible()
  await exit(page).tap()
  await expect(focus(page)).toHaveAttribute('aria-pressed','false')
  await expect(presence(page)).toBeVisible()
  await expect(cell(page,8,8,'veiled')).toBeVisible()
  expect(await fit(page)).toBe(true)
 }finally{await ctx.close()}
})

test('two actual peers see themselves and the opponent, and keyboard Focus does not break play',async({browser,baseURL})=>{
 const desk=await browser.newContext({viewport:{width:1440,height:920},reducedMotion:'reduce'}),mobile=await browser.newContext({viewport:{width:390,height:840},reducedMotion:'reduce'})
 try{
  await desk.addInitScript(()=>localStorage.setItem('imp-plan-player-wardrobe-v1','550'))
  await mobile.addInitScript(()=>localStorage.setItem('imp-plan-player-wardrobe-v1','571'))
  const host=await desk.newPage(),guest=await mobile.newPage()
  await host.goto(baseURL!);await host.getByLabel('Nickname').fill('Atlas');await host.getByRole('button',{name:'Create party',exact:true}).click()
  const code=(await host.getByTestId('room-code').textContent())!
  await guest.goto(baseURL!+'#/join?room='+code);await guest.getByLabel('Nickname').fill('Ibis')
  await guest.getByRole('button',{name:'Join party',exact:true}).click();await guest.getByRole('button',{name:'Ready up',exact:true}).click()
  await startMatch(host)
  for(const [p,you,them] of [[host,'Atlas','Ibis'],[guest,'Ibis','Atlas']] as const){
   const self=presence(p).locator('[data-match-role="self"]'),other=presence(p).locator('[data-match-role="opponent"]')
   await expect(self).toContainText(you);await expect(other).toContainText(them)
   await expect(self.locator('[data-player-look]')).toHaveCount(1)
   await expect(other.locator('[data-player-look]')).toHaveCount(1)
  }
  const hostLook=await presence(host).locator('[data-match-role="self"] [data-player-look]').getAttribute('data-player-look')
  expect(hostLook).toBe('550')
  await expect(presence(guest).locator('[data-match-role="opponent"] [data-player-look]')).toHaveAttribute('data-player-look','550')
  await expect(presence(host).locator('[data-match-role="opponent"] [data-player-look]')).toHaveAttribute('data-player-look','571')
  await focus(host).press('Enter')
  await capture(host,'desktop-focus')
  await cell(host,8,8).press('Enter')
  await expect(cell(guest,8,8,'veiled')).toBeVisible()
  await cell(host,8,9).press('Escape')
  await expect(focus(host)).toBeFocused()
  await cell(guest,9,8).click()
  await expect(cell(host,9,8,'veiled')).toBeVisible()
  expect(await fit(host)).toBe(true);expect(await fit(guest)).toBe(true)
 }finally{await Promise.all([desk.close(),mobile.close()])}
})

