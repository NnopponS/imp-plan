test('a 16-seat table keeps the real roster reachable with no page overflow',async({page})=>{
 await page.setViewportSize({width:320,height:740})
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.goto('./')
 await page.getByRole('button',{name:'Practice Time Auction',exact:true}).click()
 const bots=page.getByRole('button',{name:'Add bot',exact:true})
 await expect(bots).toBeEnabled({timeout:5000})
 for(let i=2;i<16;i++)await bots.click({timeout:5000})
 await startMatch(page)
 const other=presence(page).locator('[data-match-role="opponent"]')
 await expect(other).toHaveCount(15)
 await expect(presence(page).locator('[data-match-role="self"]')).toContainText('Player')
 const rail=presence(page).getByRole('group',{name:'Opponents',exact:true})
 expect(await rail.evaluate(el=>el.scrollWidth>el.clientWidth)).toBe(true)
 await rail.evaluate(el=>{el.scrollLeft=el.scrollWidth})
 await expect(other.last()).toBeInViewport()
 await expect(presence(page).locator('[data-match-role="self"]')).toBeInViewport()
 await focus(page).click()
 await page.getByRole('button',{name:'Pass',exact:true}).click()
 await expect(page.getByText('Sealed round 2 / 8',{exact:true})).toBeVisible()
 expect(await fit(page)).toBe(true)
})

test('Remove One keeps its real roster separate from cards, and Focus preserves the in-progress hand',async({page})=>{
 await page.setViewportSize({width:390,height:844})
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.goto('./season/2/')
 await page.getByRole('button',{name:'Practice Remove One',exact:true}).click()
 await startMatch(page)
 await expect(presence(page).locator('[data-match-role="opponent"]')).not.toHaveCount(0)
 await expect(presence(page).locator('[data-private-value]')).toHaveCount(0)
 const hand=page.getByRole('region',{name:'Remove One table'}).locator('.remove-hand')
 const first=hand.getByRole('button',{name:/Discard \d+, card 1/})
 await expect(first).toBeVisible()
 const cards=await hand.locator('[data-private-value]').evaluateAll(nodes=>nodes.map(el=>el.getAttribute('data-private-value')))
 await focus(page).click()
 expect(await hand.locator('[data-private-value]').evaluateAll(nodes=>nodes.map(el=>el.getAttribute('data-private-value')))).toEqual(cards)
 await first.click()
 await expect(page.getByText('Round 2 / 8',{exact:true})).toBeVisible()
 await expect(exit(page)).toBeVisible()
 expect(await fit(page)).toBe(true)
})
