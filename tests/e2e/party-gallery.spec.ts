import {expect,test,type Page} from '@playwright/test'

const stage=(page:Page)=>page.getByRole('region',{name:'Current table'})
const picker=(page:Page)=>page.getByRole('dialog',{name:'Choose a game'})
const seats=(page:Page)=>page.getByRole('region',{name:'Seats'})

async function createParty(page:Page,nickname:string){
 await page.goto('./')
 await page.getByLabel('Nickname').fill(nickname)
 await page.getByRole('button',{name:'Create party'}).click()
 const code=page.getByTestId('room-code')
 await expect(code).toHaveText(/^[A-Z2-9]{6}$/)
 return (await code.textContent())!
}

test('a keyboard host curates the table and a separate phone guest sees only the shared selection',async({browser,baseURL})=>{
 const hostContext=await browser.newContext({viewport:{width:1440,height:900},reducedMotion:'reduce',permissions:['clipboard-read','clipboard-write']})
 const guestContext=await browser.newContext({viewport:{width:320,height:760},hasTouch:true,isMobile:true,reducedMotion:'reduce'})
 try{
  const host=await hostContext.newPage(),guest=await guestContext.newPage()
  await createParty(host,'Example Host')
  await expect(stage(host).getByRole('heading',{name:'Blind Gomoku'})).toBeVisible()
  await host.getByRole('button',{name:'Copy invite'}).click()
  const link=await host.evaluate(()=>navigator.clipboard.readText())
  expect(link).toContain(baseURL!+'#/join?room=')
  await guest.goto(link)
  await guest.getByLabel('Nickname').fill('Example Guest')
  await guest.getByRole('button',{name:'Join party'}).tap()
  await expect(stage(guest).getByRole('heading',{name:'Blind Gomoku'})).toBeVisible()
  await expect(guest.getByRole('button',{name:'Choose game'})).toHaveCount(0)
  await expect(guest.getByLabel('Game',{exact:true})).toBeDisabled()
  const trigger=host.getByRole('button',{name:'Choose game'})
  await trigger.focus()
  await host.keyboard.press('Enter')
  const search=picker(host).getByRole('searchbox',{name:'Find a game'})
  await expect(search).toBeFocused()
  await host.keyboard.type('no game like this')
  await expect(picker(host).getByText('No games match.')).toBeVisible()
  await host.keyboard.press('Escape')
  await expect(picker(host)).toHaveCount(0)
  await expect(trigger).toBeFocused()
  await expect(stage(guest).getByRole('heading',{name:'Blind Gomoku'})).toBeVisible()

  await host.keyboard.press('Enter')
  await host.keyboard.type('mancala')
  const card=picker(host).getByRole('button',{name:/^Balance Mancala/})
  await expect(card.locator('img')).toHaveAttribute('src',/seasonal-mancala\.svg$/)
  await card.focus()
  await host.keyboard.press('Enter')
  await expect(picker(host)).toHaveCount(0)
  await expect(trigger).toBeFocused()
  for(const p of [host,guest]){
   await expect(stage(p).getByRole('heading',{name:'Balance Mancala'})).toBeVisible()
   await expect(stage(p).locator('img[data-arena-art]')).toHaveAttribute('src',/seasonal-mancala\.svg$/)
   await expect(p.locator('[data-game-preview]')).toHaveCount(0)
   await expect(p.getByLabel('Game',{exact:true})).toHaveValue('mancala')
  }
  const guestSeat=seats(host).getByRole('listitem').filter({hasText:'Example Guest'})
  await expect(guestSeat).toContainText('Not ready')
  await expect(host.getByRole('button',{name:'Start match',exact:true})).toBeDisabled()
  const preview=guest.getByRole('button',{name:'Details',exact:true})
  await preview.tap()
  const briefing=guest.getByRole('dialog',{name:'Balance Mancala'})
  await expect(briefing).toBeVisible()
  await expect(briefing.locator('[data-game-preview="mancala"]')).toBeVisible()
  await guest.getByRole('button',{name:'Back to lobby'}).tap()
  await expect(preview).toBeFocused()
  await guest.getByRole('button',{name:'Ready up'}).tap()
  await expect(guestSeat).toContainText('Ready')
  await host.getByRole('button',{name:'Add bot'}).click()
  await expect(seats(guest).getByRole('listitem').filter({hasText:'Bot ready'})).toHaveCount(1)
  await guest.getByRole('textbox',{name:'Message'}).fill('Ready for this table')
  await guest.getByRole('button',{name:'Send',exact:true}).tap()
  await expect(host.getByRole('log')).toContainText('Ready for this table')
  expect(await guest.evaluate(()=>document.documentElement.scrollWidth)).toBe(320)
  await host.getByRole('button',{name:'Start match',exact:true}).click()
  await host.getByRole('button',{name:'Enter match',exact:true}).click()
  await expect(guest.getByRole('heading',{name:'Balance Mancala',level:1})).toBeVisible()
 }finally{await Promise.all([hostContext.close(),guestContext.close()])}
})

test('a 320px touch host filters the image-first shelf by season and switches games',async({browser})=>{
 const context=await browser.newContext({viewport:{width:320,height:710},hasTouch:true,isMobile:true,reducedMotion:'reduce'})
 try{
  const host=await context.newPage()
  await createParty(host,'Example Phone')
  await host.getByRole('button',{name:'Choose game'}).tap()
  const dialog=picker(host)
  await dialog.getByRole('button',{name:'Season 2',exact:true}).tap()
  await expect(dialog.getByRole('button',{name:'Season 2',exact:true})).toHaveAttribute('aria-pressed','true')
  await expect(dialog.getByRole('button',{name:/^Blind Gomoku/})).toHaveCount(0)
  const search=dialog.getByRole('searchbox',{name:'Find a game'})
  await search.fill("Knight's Tour")
  await expect(dialog.getByRole('button',{name:/^Knight’s Tour/})).toBeVisible()
  await expect(dialog.getByText('1 game',{exact:true})).toBeVisible()
  await search.fill('')
  const card=dialog.getByRole('button',{name:/^Time Auction/})
  await expect(card.locator('img')).toHaveAttribute('src',/seasonal-auction\.svg$/)
  expect(await dialog.evaluate(node=>node.scrollWidth<=node.clientWidth)).toBe(true)
  const details=dialog.getByRole('button',{name:'Details for Time Auction',exact:true})
  await details.tap()
  const gameDetails=host.getByRole('dialog',{name:'Time Auction',exact:true})
  await expect(gameDetails.locator('[data-game-preview="auction"]')).toBeVisible()
  await expect(host.getByLabel('Game',{exact:true})).toHaveValue('blind')
  await gameDetails.getByRole('button',{name:'Close details',exact:true}).tap()
  await expect(gameDetails).toHaveCount(0)
  await expect(details).toBeFocused()
  await card.tap()
  await expect(dialog).toHaveCount(0)
  await expect(stage(host).getByRole('heading',{name:'Time Auction'})).toBeVisible()
  await expect(host.locator('[data-game-preview]')).toHaveCount(0)
  await expect(host.getByLabel('Time Auction mode')).toBeVisible()
  expect(await host.evaluate(()=>document.documentElement.scrollWidth)).toBe(320)
 }finally{await context.close()}
})
