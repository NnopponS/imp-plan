import {expect,test} from '@playwright/test'

test('invited guests can preview rules before readying and rejoin the match view if the host starts',async({browser,baseURL})=>{
 const hc=await browser.newContext(),gc=await browser.newContext({viewport:{width:360,height:740},hasTouch:true})
 const host=await hc.newPage(),guest=await gc.newPage()
 try{
  await host.goto(baseURL!)
  await host.getByLabel('Nickname').fill('Host')
  await host.getByRole('button',{name:'Create party'}).click()
  const code=await host.getByTestId('room-code').innerText()
  await guest.goto(baseURL!+'#/join?room='+code)
  await guest.getByLabel('Nickname').fill('Guest')
  await guest.getByRole('button',{name:'Join party'}).click()
  const preview=guest.getByRole('button',{name:'Details',exact:true})
  await expect(preview).toBeVisible({timeout:3000})
  await preview.click()
  const dialog=guest.getByRole('dialog',{name:'Blind Gomoku'})
  await expect(dialog.getByText('2 at the table')).toBeVisible()
  await expect(dialog.getByText('2 humans · 0 bots')).toBeVisible()
  const rule=dialog.locator('.brief-lesson button').nth(1)
  await rule.click()
  await expect(rule).toHaveAttribute('aria-pressed','true')
  await expect(dialog.getByRole('button',{name:'Enter match',exact:true})).toHaveCount(0)
  await expect(host.getByRole('button',{name:'Start match',exact:true})).toBeDisabled()
  await guest.keyboard.press('Escape')
  await expect(preview).toBeFocused()
  await guest.getByRole('button',{name:'Ready up'}).click()
  await preview.click()
  await expect(dialog).toBeVisible()
  await host.getByRole('button',{name:'Start match',exact:true}).click()
  await host.getByRole('dialog').getByRole('button',{name:'Enter match',exact:true}).click()
  await expect(dialog).toHaveCount(0)
  await expect(guest.getByRole('heading',{name:'Blind Gomoku',level:1})).toBeFocused()
  await expect(guest.getByRole('button',{name:'Row 8, column 8, open'})).toBeVisible()
 }finally{await Promise.all([hc.close(),gc.close()])}
})
