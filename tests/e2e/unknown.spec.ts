import {expect,test,type Page} from '@playwright/test'
import {chooseGame} from '../lobby-controls'
import {startMatch} from './start-match'

const table=(p:Page)=>p.locator('.room[data-playing]:not([inert]) [data-unknown-table]')
const cover=(p:Page)=>p.getByRole('button',{name:'Open Unknown',exact:true})
const art=(p:Page)=>p.locator('[data-preview-game="unknown"]:visible img[data-arena-art]').first()
const seatOne=(p:Page)=>table(p).locator('[data-unknown-cube="1"]')

test('320px practice uses real shared mosaic and swiped lessons, then completes a race',async({browser,baseURL},info)=>{
 test.setTimeout(60_000)
 const context=await browser.newContext({viewport:{width:320,height:640},isMobile:true,hasTouch:true,reducedMotion:'reduce'})
 try{
  const p=await context.newPage()
  const errors:string[]=[]
  p.on('pageerror',e=>errors.push(e.message))
  await p.clock.install()
  await p.goto(baseURL!+'season/2/')
  await cover(p).scrollIntoViewIfNeeded()
  await expect.poll(()=>art(p).evaluate((img:HTMLImageElement)=>img.complete&&img.naturalWidth>0)).toBe(true)
  await cover(p).tap()
  const details=p.getByRole('dialog',{name:'Unknown',exact:true})
  const preview=details.locator('[data-real-table-preview="unknown"]')
  const sample=preview.locator('[data-unknown-mosaic]')
  await expect(sample).toBeVisible()
  await expect(sample.locator('[data-unknown-cube="1"]')).toHaveAttribute('data-cell','9')
  expect(await sample.evaluate(node=>!!node.closest('[inert]'))).toBe(true)
  await sample.screenshot({path:info.outputPath('unknown-actual-preview.png')})
  await details.getByRole('button',{name:'Practice Unknown',exact:true}).tap()
  await expect(p.getByRole('textbox',{name:'Nickname'})).toHaveCount(0)
  await expect(p.getByRole('button',{name:'Remove Bot 1 from seat 2'})).toBeVisible()
  await p.getByRole('button',{name:'Start match',exact:true}).tap()
  const briefing=p.getByRole('dialog'),guide=briefing.getByRole('region',{name:'How to play'})
  await expect(guide.locator('[data-unknown-lesson="0"]')).toBeVisible()
  await expect(briefing.getByRole('button',{name:/^(Back|Next)$/i})).toHaveCount(0)
  await guide.press('ArrowRight')
  await expect(guide.locator('[data-unknown-lesson="1"] [data-unknown-cube="1"]')).toHaveAttribute('data-cell','9')
  const swipe=guide.locator('.brief-pages')
  const surface=await swipe.count()?swipe:guide.locator('.brief-theater-scene')
  const rect=await surface.boundingBox()
  expect(rect).toBeTruthy()
  const x=rect!.x+rect!.width*.3,y=rect!.y+rect!.height*.45
  const cdp=await context.newCDPSession(p)
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x,y}]})
  await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:x+80,y}]})
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
  await expect(guide.locator('[data-unknown-lesson="2"] [data-unknown-cube="2"]')).toHaveAttribute('data-cell','18')
  await guide.press('ArrowRight')
  await expect(guide.locator('[data-unknown-lesson="3"] [data-unknown-cube="1"]')).toHaveAttribute('data-cell','24')
  await briefing.getByRole('button',{name:'Enter match',exact:true}).tap()
  const live=table(p)
  await expect(live.locator('[data-unknown-mosaic]')).toHaveAttribute('viewBox','0 0 420 420')
  await expect(live.getByText('Your roll',{exact:true})).toBeVisible()
  await expect(seatOne(p)).toHaveAttribute('data-cell','2')
  await live.locator('[data-roll=south]').tap()
  await expect(live.locator('.unknown-observation')).toContainText('rolled Sun')
  expect(await p.evaluate(()=>document.documentElement.scrollWidth)).toBe(320)
  await p.screenshot({path:info.outputPath('unknown-mobile-after-roll.png')})
  for(let i=0;i<40&&await live.getAttribute('data-stage')!=='finished';i++){
   const action=live.locator('[data-roll]:enabled').first()
   if(await action.count())await action.tap()
   else if(await live.getByRole('button',{name:'Pass blocked turn'}).count())await live.getByRole('button',{name:'Pass blocked turn'}).tap()
   await p.clock.fastForward(800)
  }
  await expect(live).toHaveAttribute('data-stage','finished')
  await expect(live.getByRole('list',{name:'Final cube positions'}).getByRole('listitem')).toHaveCount(2)
  await expect(p.getByRole('region',{name:'Match record'})).toBeVisible()
  await expect(live.locator('.unknown-laws summary')).toContainText('3 / 3')
  expect(errors).toEqual([])
 }finally{await context.close()}
})

test('room turn ownership and roll outcomes synchronize in two isolated browser contexts',async({browser,baseURL})=>{
 test.setTimeout(60_000)
 const contexts=await Promise.all([browser.newContext({reducedMotion:'reduce'}),browser.newContext({reducedMotion:'reduce',viewport:{width:390,height:800},hasTouch:true})])
 try{
  const [host,guest]=await Promise.all(contexts.map(c=>c.newPage()))
  await host.goto(baseURL!)
  await host.getByLabel('Nickname').fill('Keeper')
  await host.getByRole('button',{name:'Create party',exact:true}).click()
  const code=await host.getByTestId('room-code').textContent()
  await chooseGame(host,'unknown')
  await guest.goto(baseURL!+'#/join?room='+code)
  await guest.getByLabel('Nickname').fill('Guest')
  await guest.getByRole('button',{name:'Join party',exact:true}).tap()
  await guest.getByRole('button',{name:'Ready up',exact:true}).tap()
  await startMatch(host)
  await expect(table(guest)).toBeVisible()
  await expect(table(guest).locator('[data-roll]')).toHaveCount(0)
  await expect(table(guest).locator('.unknown-laws summary')).toContainText('0 / 3')
  await table(host).locator('[data-roll=south]').click()
  await expect(table(guest).locator('.unknown-observation')).toContainText('Keeper rolled Sun')
  if(await table(host).getByText(/Echo roll/).count())await table(host).locator('[data-roll]:enabled').first().click()
  await expect(table(guest).locator('[data-roll=north]')).toBeEnabled()
  await expect(table(host).locator('[data-roll]')).toHaveCount(0)
  await table(guest).locator('[data-roll=north]').tap()
  await expect(table(host).locator('.unknown-observation')).toContainText('Guest rolled Sun')
  await expect(table(host).locator('.unknown-laws summary')).toContainText('0 / 3')
  expect(await seatOne(host).getAttribute('data-cell')).toEqual(await seatOne(guest).getAttribute('data-cell'))
 }finally{await Promise.all(contexts.map(c=>c.close()))}
})
