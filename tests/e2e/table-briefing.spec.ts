test('sixteen actual seats fit in the mobile briefing and can still be dismissed',async({page})=>{
 await page.setViewportSize({width:360,height:740})
 await page.goto('./')
 await page.getByLabel('Nickname').fill('Host')
 await page.getByRole('button',{name:'Practice Time Auction',exact:true}).click()
 for(let i=2;i<16;i++)await page.getByRole('button',{name:'Add bot',exact:true}).click()
 await page.getByRole('button',{name:'Start match',exact:true}).click()
 const briefing=page.getByRole('dialog',{name:'Time Auction'})
 await expect(briefing.getByText('16 at the table')).toBeVisible()
 await expect(briefing.getByText('1 human · 15 bots')).toBeVisible()
 await expect(briefing.locator('[data-brief-seat]')).toHaveCount(16)
 expect(await briefing.evaluate(el=>el.scrollWidth)).toBe(await briefing.evaluate(el=>el.clientWidth))
 await page.keyboard.press('Escape')
 await expect(briefing).toHaveCount(0)
})
