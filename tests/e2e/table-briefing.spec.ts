test('Hexagon briefing animates only the worked example and uses a true contiguous sum',async({page})=>{
 await page.clock.install({time:new Date('2026-01-01T00:00:00Z')})
 await page.clock.pauseAt(new Date('2026-01-01T00:01:00Z'))
 await page.goto('./',{waitUntil:'domcontentloaded'})
 await page.getByRole('button',{name:'Practice Hexagon',exact:true}).press('Enter')
 await page.getByRole('button',{name:'Start match',exact:true}).press('Enter')
 const brief=page.getByRole('dialog',{name:'Hexagon'})
 const shot=brief.locator('.hex-brief-shot')
 await expect(shot).toHaveAttribute('data-hex-step','study')
 const pieces=shot.locator('[data-hex-cell]')
 await expect(pieces).toHaveCount(19)
 const values=await pieces.locator('text').allTextContents()
 expect(values.every(value=>Number(value)>=1&&Number(value)<=20)).toBe(true)
 await page.clock.runFor(3150)
 await expect(shot).toHaveAttribute('data-hex-step','study')
 await brief.getByRole('region',{name:'How to play'}).press('ArrowRight')
 await expect(shot).toHaveAttribute('data-hex-step','veil')
 expect(await pieces.locator('text').allTextContents()).toEqual(Array.from('ABCDEFGHIJKLMNOPQRS'))
 await brief.getByRole('region',{name:'How to play'}).press('ArrowRight')
 await expect(shot).toHaveAttribute('data-hex-step','line')
 const line=await shot.locator('[data-hex-pick]').evaluateAll(nodes=>nodes.map(n=>Number(n.getAttribute('data-hex-cell'))))
 const {hexLines}=await import('../../src/puzzles')
 expect(hexLines().some(candidate=>candidate.length===line.length&&candidate.every(i=>line.includes(i)))).toBe(true)
 expect(line.reduce((a,i)=>a+Number(values[i]),0)).toBe(Number(await shot.getByTestId('hex-example-target').textContent()))
 await expect(brief.getByRole('timer')).toHaveCount(0)
 await expect(page.getByRole('region',{name:'Hexagon instrument',includeHidden:true})).toHaveCount(0)
 await brief.getByRole('region',{name:'How to play'}).press('Home')
 await expect(shot).toHaveAttribute('data-hex-step','study')
 await page.clock.runFor(6500)
 await expect(shot).toHaveAttribute('data-hex-step','study')
 await brief.getByRole('button',{name:'Enter match'}).press('Enter')
 await page.clock.resume()
 await expect(page.getByRole('region',{name:'Hexagon instrument'}).getByRole('timer')).toBeVisible()
})

for(const [width,height,mode] of [[320,568,'system'],[844,390,'off'],[1440,900,'off']] as const){
 test(`Hexagon lesson fits ${width}×${height} without autoplay when motion is reduced`,async({page})=>{
  await page.setViewportSize({width,height})
  if(mode==='system')await page.emulateMedia({reducedMotion:'reduce'})
  else await page.addInitScript(()=>localStorage.setItem('imp-plan-feedback-v1',JSON.stringify({sound:false,motion:'off'})))
  await page.clock.install()
  await page.goto('./',{waitUntil:'domcontentloaded'})
  await page.getByRole('button',{name:'Practice Hexagon',exact:true}).click()
  await page.getByRole('button',{name:'Start match',exact:true}).click()
  const brief=page.getByRole('dialog',{name:'Hexagon'})
  const shot=brief.locator('.hex-brief-shot')
  await page.clock.runFor(6500)
  await expect(shot).toHaveAttribute('data-hex-step','study')
  await expect(brief.getByRole('button',{name:/Pause example|Replay example/})).toHaveCount(0)
  await brief.getByRole('region',{name:'How to play'}).press('End')
  await expect(brief.getByRole('heading',{name:'Choose a line'})).toBeVisible()
  await expect(shot.getByRole('img',{name:/Hexagon example:/})).toBeInViewport({ratio:1})
  await expect(brief.getByRole('button',{name:'Enter match'})).toBeInViewport({ratio:1})
  expect(await brief.evaluate(node=>node.scrollWidth)).toBe(await brief.evaluate(node=>node.clientWidth))
  expect(await brief.evaluate(node=>node.getAnimations({subtree:true}).filter(a=>a.playState==='running').length)).toBe(0)
 })
}

for(const [width,height] of [[320,568],[390,844],[844,390]] as const){
 test(`Blind Gomoku's briefing has one stage and keeps its actions in reach at ${width}×${height}`,async({page},info)=>{
  await page.setViewportSize({width,height})
  await page.goto('./')
  await page.getByRole('button',{name:'Practice Blind Gomoku',exact:true}).click()
  await page.getByRole('button',{name:'Start match',exact:true}).click()
  const brief=page.getByRole('dialog',{name:'Blind Gomoku'})
  const board=brief.locator('[data-rule-demo=blind] svg')
  const action=brief.getByRole('button',{name:'Enter match'})
  const skip=brief.getByRole('button',{name:'Skip entrance'})
  await expect(brief.locator('.brief-theater-scene img[src$="secret-chamber.svg"]')).toHaveCount(1)
  await expect(action).toBeInViewport({ratio:1})
  await expect(brief.getByRole('button',{name:'Back to setup'})).toBeInViewport({ratio:1})
  await expect(board).toBeInViewport({ratio:1})
  expect((await board.boundingBox())?.width??0).toBeGreaterThanOrEqual(166)
  expect(await brief.evaluate(el=>el.scrollWidth)).toBe(await brief.evaluate(el=>el.clientWidth))
  await brief.screenshot({path:info.outputPath('briefing.png'),animations:'disabled'})
  await skip.click()
  await expect(skip).toHaveCount(0)
  await expect(action).toBeFocused()
  await expect(board).toBeInViewport({ratio:1})
  await expect(brief.getByRole('timer')).toHaveCount(0)
  await brief.getByRole('region',{name:'How to play'}).press('ArrowRight')
  await brief.getByRole('region',{name:'How to play'}).press('ArrowRight')
  await expect(brief.getByRole('heading',{name:'Make five'})).toBeVisible()
  await expect(board).toHaveAccessibleName(/five circle stones form a line/)
  await expect(action).toBeInViewport({ratio:1})
  await page.keyboard.press('Escape')
  await expect(brief).toHaveCount(0)
  await expect(page.getByRole('button',{name:'Start match',exact:true})).toBeFocused()
 })
}
