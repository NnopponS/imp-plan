import {test,expect} from '@playwright/test'

test('gallery search filters playable cards without leaving the season',async({page})=>{
 await page.setViewportSize({width:390,height:844})
 await page.goto('./season/1/')
 await page.getByRole('searchbox',{name:'Find playable games'}).fill('morris')
 await expect(page.locator('.featured .card')).toHaveCount(1)
 await expect(page.getByRole('button',{name:'Practice Nine Men’s Morris'})).toBeVisible()
 await expect(page).toHaveURL(/\/season\/1\/$/)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(390)
})

test('briefing counts actual seats, explains the game, and does not start until confirmed',async({page})=>{
 await page.setViewportSize({width:390,height:844})
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.goto('./')
 await page.getByLabel('Nickname').fill('Designer')
 await page.getByRole('button',{name:'Practice Blind Gomoku'}).click()
 await page.getByLabel('Bot difficulty').selectOption('easy')
 await page.getByRole('button',{name:'Start match',exact:true}).click()
 const briefing=page.getByRole('dialog',{name:'Blind Gomoku'})
 await expect(briefing.getByText('2 at the table')).toBeVisible()
 await expect(briefing.getByText('1 human · 1 bot')).toBeVisible()
 await expect(briefing.locator('[data-brief-seat]')).toHaveCount(2)
 await expect(briefing.locator('[data-brief-seat]').first()).toHaveCSS('animation-name','none')
 await expect(briefing.getByRole('button',{name:/15 × 15 board/})).toBeVisible()
 await expect(page.getByLabel('Blind Gomoku board')).toHaveCount(0)
 await briefing.getByRole('button',{name:'Back to setup'}).click()
 await expect(page.getByRole('button',{name:'Start match',exact:true})).toBeFocused()
 await page.getByRole('button',{name:'Start match',exact:true}).click()
 await briefing.getByRole('button',{name:'Enter match'}).click()
 await expect(page.getByRole('button',{name:'Row 8, column 8, open'})).toBeVisible()
})

