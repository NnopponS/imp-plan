import {expect,test} from '@playwright/test'

for(const [width,height] of [[320,690],[768,900],[911,892],[1440,950]]){
 test(`codex folios keep the art, entrances and real controls usable at ${width}px`,async({page})=>{
  await page.setViewportSize({width,height})
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.goto('./')
  const hero=page.locator('.painted-desk')
  const picture=hero.locator('.landing-painting')
  await expect(hero.locator('.codex-spread')).toHaveAttribute('aria-hidden','true',{timeout:3000})
  expect(await picture.evaluate(node=>getComputedStyle(node).clipPath)).toContain('codex-leaves')
  const contour=hero.locator('.codex-leaf-outline')
  const bottomEdge=await contour.evaluate((path:SVGPathElement)=>{
   const length=path.getTotalLength()
   return Array.from({length:500},(_,i)=>path.getPointAtLength(length*i/500)).filter(point=>point.x>490&&point.x<510).reduce((max,point)=>Math.max(max,point.y),0)
  })
  // The bottom edge actually curves downward to the binding, not a box outline.
  expect(bottomEdge).toBeGreaterThan(350)
  const warm=page.getByRole('region',{name:'One-move warm-up'})
  const cell=warm.getByRole('button',{name:'Row 8, column 9, empty'})
  await expect(cell).toBeInViewport()
  await cell.click()
  await expect(warm.getByRole('status')).toHaveText('Five in a row. You win!')
  await expect(warm.getByRole('button',{name:'Reset warm-up'})).toBeFocused()
  await warm.getByRole('button',{name:'Reset warm-up'}).press('Enter')
  await expect(warm.getByRole('button',{name:'Row 6, column 4, empty'})).toBeFocused()
  const browse=page.getByRole('link',{name:'Browse games',exact:true})
  await browse.focus()
  await page.keyboard.press('Enter')
  const search=page.getByRole('searchbox',{name:'Find playable games'})
  await expect(search).toBeInViewport()
  await search.click()
  await search.fill('Blind Gomoku')
  await expect(page.getByRole('button',{name:'Practice Blind Gomoku',exact:true})).toBeVisible()
  const entry=page.getByRole('link',{name:'Create or join a room',exact:true})
  await entry.focus()
  await page.keyboard.press('Enter')
  await page.keyboard.press('Tab')
  const nickname=page.getByRole('textbox',{name:'Nickname'})
  await expect(nickname).toBeFocused()
  await nickname.click()
  await nickname.fill('Night Archivist')
  await expect(nickname).toHaveValue('Night Archivist')
  const season=page.locator('.season-directory').getByRole('link',{name:/The First Plan/})
  await season.focus()
  expect(await season.evaluate(node=>getComputedStyle(node).outlineStyle)).not.toBe('none')
  await season.press('Enter')
  await expect(page.getByRole('heading',{name:'The First Plan'})).toBeVisible()
  const launch=page.getByRole('button',{name:'Practice Blind Gomoku',exact:true})
  await expect(launch).toBeInViewport({ratio:1})
  await launch.click()
  await expect(page.getByRole('heading',{name:'Practice lobby'})).toBeVisible()
  await page.getByRole('button',{name:'Start match',exact:true}).click()
  await expect(page.getByRole('dialog',{name:'Blind Gomoku'})).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(width)
 })
}

test.describe('touch on the narrow codex',()=>{
 test.use({viewport:{width:320,height:690},hasTouch:true,isMobile:true})
 test('warm-up, anchor and room inputs all respond to touch',async({page})=>{
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.goto('./')
  const warm=page.getByRole('region',{name:'One-move warm-up'})
  await warm.getByRole('button',{name:'Row 8, column 9, empty'}).tap()
  await expect(warm.getByRole('status')).toHaveText('Five in a row. You win!')
  await page.getByRole('link',{name:'Create or join a room',exact:true}).tap()
  const code=page.getByRole('textbox',{name:'Invite code'})
  await code.tap()
  await expect(code).toBeFocused()
 })
})
