import {expect,test,type Page} from '@playwright/test'
import {chooseGame} from '../lobby-controls'
import {startMatch} from './start-match'

const chart=(p:Page)=>p.locator('.room[data-playing]:not([data-sample-table]) .island-table')
const button=(p:Page,name:string)=>chart(p).getByRole('button',{name,exact:true})
const controls=(p:Page)=>chart(p).getByRole('group',{name:'Rotate and lay selected arrow'})

test('same illustrated preview, mobile swipe guide and live chart; solo routes reach a genuine result',async({browser,baseURL},info)=>{
 test.setTimeout(120000)
 const context=await browser.newContext({viewport:{width:320,height:760},isMobile:true,hasTouch:true,reducedMotion:'reduce'})
 try{
  const p=await context.newPage()
  await p.goto(baseURL!+'season/2/')
  await p.locator('#play input[type=search]').fill('Treasure Island')
  const card=p.getByRole('article').filter({has:p.getByRole('heading',{name:'Treasure Island',exact:true})})
  const cover=card.locator('img[data-arena-art]')
  await expect(cover).toHaveAttribute('src',/seasonal-treasureIsland\.svg$/)
  await expect.poll(()=>cover.evaluate((e:HTMLImageElement)=>e.complete&&e.naturalWidth>0)).toBe(true)
  await card.getByRole('button',{name:'Open Treasure Island',exact:true}).tap()
  const dialog=p.getByRole('dialog',{name:'Treasure Island',exact:true})
  const preview=dialog.locator('[data-real-table-preview=treasureIsland] [data-island-map]')
  await expect(preview).toBeVisible()
  expect(await preview.evaluate(el=>el.closest('[inert]')!==null)).toBe(true)
  const pattern=(map:typeof preview)=>map.locator('[data-island-tile]').evaluateAll(els=>els.map(e=>e.getAttribute('data-island-tile')).join(','))
  const geometry=await pattern(preview)
  expect(geometry.split(',')).toHaveLength(81)
  await expect(dialog.getByRole('timer',{includeHidden:true})).toHaveCount(0)
  await dialog.screenshot({path:info.outputPath('island-mobile-preview.png')})
  await dialog.getByRole('button',{name:'Practice Treasure Island',exact:true}).tap()
  await p.getByRole('button',{name:'Start match',exact:true}).tap()
  const lesson=p.getByRole('region',{name:'How to play'})
  await expect(lesson).toHaveAttribute('data-lesson-kind','worked-example')
  await expect(lesson.getByRole('heading',{name:'Bid on one arrow'})).toBeVisible()
  await expect(lesson.locator('.brief-cue')).toHaveAttribute('data-ready','true')
  expect(await pattern(lesson.locator('[data-island-map]'))).toBe(geometry)
  await expect(chart(p)).toHaveCount(0)
  await expect(p.getByRole('timer')).toHaveCount(0)
  const b=await lesson.locator('.brief-page').boundingBox()
  const session=await context.newCDPSession(p)
  const x=b!.x+b!.width*.22,y=b!.y+40
  await session.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x,y}]})
  await session.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:x+82,y}]})
  await session.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
  await session.detach()
  await expect(lesson.getByRole('heading',{name:'Lay a route from E5'})).toBeVisible()
  await lesson.press('ArrowRight')
  await expect(lesson.getByRole('heading',{name:'Read your private compass'})).toBeVisible()
  await lesson.press('End')
  await expect(lesson.getByRole('heading',{name:'Recover the treasure'})).toBeVisible()
  await expect(lesson.getByRole('button',{name:/^(Back|Next)$/})).toHaveCount(0)
  await p.getByRole('dialog').screenshot({path:info.outputPath('island-mobile-guide.png')})
  await p.getByRole('dialog').getByRole('button',{name:'Enter match',exact:true}).tap()
  await expect(chart(p)).toHaveAttribute('data-island-phase','auction')
  expect(await pattern(chart(p).locator('[data-island-map]'))).toBe(geometry)
  await expect(chart(p).getByRole('timer')).toBeVisible()
  await expect(chart(p).getByLabel('Bid amount')).toBeVisible()
  await button(p,'Raise your bid').tap()
  await expect(chart(p).getByLabel('Bid amount')).toHaveValue('2')
  await button(p,'Seal bid').tap()
  await expect(chart(p).locator('.island-kicker').first()).toHaveText('SEALED LOT 2 / 2')
  await expect(chart(p)).toContainText('13 chips')
  await button(p,'Seal bid').tap()
  await expect(chart(p)).toHaveAttribute('data-island-phase','explore')
  await controls(p).getByRole('button',{name:'North'}).tap()
  await expect(chart(p)).toContainText('Dig at E4.')
  await button(p,'Undo arrow').tap()
  await expect(button(p,'Seal route')).toBeDisabled()
  await controls(p).getByRole('button',{name:'North'}).tap()
  expect((await button(p,'Seal route').boundingBox())!.height).toBeGreaterThanOrEqual(44)
  await expect(chart(p).getByRole('img',{name:/Current route ends at E4/})).toBeVisible()
  await chart(p).screenshot({path:info.outputPath('island-mobile-route.png')})
  await button(p,'Seal route').tap()
  await expect(chart(p).locator('.island-notebook')).toContainText(/E4.*Cache/)
  for(let n=2;n<=5;n++){
   await expect(chart(p).locator('.island-kicker').first()).toHaveText('EXPEDITION '+n+' / 5')
   await button(p,'Pass dig').tap()
  }
  await expect(chart(p).getByRole('heading',{name:'Practice complete'})).toBeVisible()
  await expect(chart(p).getByRole('region',{name:'Island standings'})).toContainText(/1 cache/)
  await expect(p.getByRole('region',{name:'Match record'})).toBeVisible()
  expect(await p.evaluate(()=>document.documentElement.scrollWidth)).toBe(320)
  await chart(p).screenshot({path:info.outputPath('island-mobile-results.png')})
 }finally{await context.close()}
})

test('two live browser seats see only their own bids and notebook, then agree on the standings',async({browser,baseURL},info)=>{
 test.setTimeout(120000)
 const contexts=await Promise.all([browser.newContext({viewport:{width:1440,height:900},reducedMotion:'reduce'}),browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,reducedMotion:'reduce'})])
 try{
  const [host,guest]=await Promise.all(contexts.map(c=>c.newPage()))
  await host.goto(baseURL!)
  await host.getByLabel('Nickname').fill('Ada')
  await host.getByRole('button',{name:'Create party'}).click()
  await chooseGame(host,'treasureIsland')
  const code=(await host.getByTestId('room-code').textContent())!
  await guest.goto(baseURL!+'#/join?room='+code)
  await guest.getByLabel('Nickname').fill('Bo')
  await guest.getByRole('button',{name:'Join party',exact:true}).tap()
  await guest.getByRole('button',{name:'Ready up',exact:true}).tap()
  await startMatch(host)
  await expect(chart(guest)).toHaveAttribute('data-island-phase','auction')
  await chart(host).getByLabel('Bid amount').fill('5')
  await button(host,'Seal bid').click()
  await expect(chart(host)).toContainText('Your 5-chip bid is sealed.')
  await expect(chart(guest)).toContainText('1 of 2 sealed')
  await expect(chart(guest)).not.toContainText('5-chip')
  await chart(host).screenshot({path:info.outputPath('island-desktop-market.png')})
  await button(guest,'Pass lot').tap()
  for(let used=2;used<=4;used++){
   const lot='SEALED LOT '+used+' / 4'
   await expect(chart(host).locator('.island-kicker').first()).toHaveText(lot)
   await expect(chart(guest).locator('.island-kicker').first()).toHaveText(lot)
   await button(host,'Pass lot').click()
   await button(guest,'Pass lot').tap()
  }
  await expect(chart(host)).toHaveAttribute('data-island-phase','explore')
  await expect(chart(guest)).toHaveAttribute('data-island-phase','explore')
  await controls(host).getByRole('button',{name:'North'}).click()
  await button(host,'Seal route').click()
  await expect(chart(host)).toContainText('Route to E4 sealed.')
  await expect(chart(guest)).not.toContainText('E4')
  await button(guest,'Pass dig').tap()
  await expect(chart(host).locator('.island-notebook')).toContainText('E4')
  await expect(chart(guest).locator('.island-notebook')).not.toContainText('E4')
  await chart(host).screenshot({path:info.outputPath('island-desktop-clue.png')})
  for(let round=2;round<=5;round++){
   await expect(chart(host).locator('.island-kicker').first()).toHaveText('EXPEDITION '+round+' / 5')
   await expect(chart(guest).locator('.island-kicker').first()).toHaveText('EXPEDITION '+round+' / 5')
   await button(host,'Pass dig').click()
   await button(guest,'Pass dig').tap()
  }
  const results=chart(host).getByRole('region',{name:'Island standings'})
  await expect(results.getByRole('heading',{name:'Ada wins'})).toBeVisible()
  expect(await chart(guest).getByRole('region',{name:'Island standings'}).textContent()).toBe(await results.textContent())
  await chart(host).screenshot({path:info.outputPath('island-desktop-standings.png')})
 }finally{await Promise.all(contexts.map(c=>c.close()))}
})
