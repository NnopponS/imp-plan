import {test,expect} from '@playwright/test'
import {startMatch} from './start-match'

test('Divine solo starter puts the first move, numerical value and key in reach on a short phone',async({page})=>{
 await page.setViewportSize({width:320,height:568})
 await page.goto('./season/3/')
 await page.getByRole('button',{name:'Practice Divine Test',exact:true}).click()
 await expect(page.getByLabel('Square size')).toHaveValue('3',{timeout:2500})
 const sizeLabels=await page.getByLabel('Square size').locator('option').allTextContents()
 expect(sizeLabels).toEqual(['3 × 3 (starter)','5 × 5','7 × 7'])
 await startMatch(page)
 await page.evaluate(()=>window.scrollTo(0,0))
 const grid=page.getByRole('region',{name:'Magic square grid'})
 const tray=page.getByRole('region',{name:'Tile tray'})
 const first=tray.getByRole('button',{name:/^Tile .+, value \d+$/}).first()
 const empty=grid.getByRole('button',{name:/empty$/}).first()
 await expect(grid.getByRole('button')).toHaveCount(9)
 await expect(grid).toBeInViewport({ratio:1})
 await expect(first).toBeInViewport({ratio:1})
 await expect(empty).toBeInViewport({ratio:1})
 await expect(page.getByRole('button',{name:'Numeral legend'})).toBeInViewport({ratio:1})
 const tile=await first.getAttribute('aria-label')
 await first.click()
 await expect(page.getByRole('status').filter({hasText:/Selected .+, value \d+/})).toBeVisible()
 await empty.click()
 const placed=grid.getByRole('button',{name:': '+tile!.slice(5),exact:false})
 await expect(placed).toHaveCount(1)
 await page.getByRole('button',{name:'Eraser'}).click()
 await placed.click()
 await expect(placed).toHaveCount(0)

 await first.focus()
 await page.keyboard.press('Enter')
 const initial=grid.locator('button:focus')
 await expect(initial).toHaveCount(1)
 const from=Number(await initial.getAttribute('data-cell'))
 const row=Math.floor(from/3)*3
 const candidate=row+(from+1)%3
 const next=await grid.locator('button[data-cell="'+candidate+'"]').isDisabled()?row+(from+2)%3:candidate
 await page.keyboard.press('ArrowRight')
 await expect(grid.locator('button[data-cell="'+next+'"]')).toBeFocused()
 await page.keyboard.press('Escape')
 await expect(page.getByRole('status').filter({hasText:'Pick a tile'})).toBeVisible()
 await page.keyboard.press('Enter')
 await expect(placed).toHaveCount(0)

 await first.dragTo(empty)
 await expect(placed).toHaveCount(1)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(320)
})

test('Divine online defaults to 7×7 and the on-screen hard rack never decodes its symbols',async({browser,baseURL})=>{
 const hctx=await browser.newContext({viewport:{width:320,height:568},hasTouch:true})
 const gctx=await browser.newContext({viewport:{width:320,height:568},hasTouch:true})
 try{
  const host=await hctx.newPage(),guest=await gctx.newPage()
  await host.goto(baseURL!+'season/3/')
  await host.getByLabel('Nickname').fill('Keeper')
  await host.getByRole('button',{name:'Create party'}).click()
  const code=await host.getByTestId('room-code').textContent()
  await host.getByLabel('Game').selectOption('divine')
  await expect(host.getByLabel('Square size')).toHaveValue('7')
  await host.getByLabel('Deduce the numeral key').check()
  await guest.goto(baseURL!+'#/join?room='+code)
  await guest.getByLabel('Nickname').fill('Guest')
  await guest.getByRole('button',{name:'Join party'}).click()
  await guest.getByRole('button',{name:'Ready up'}).click()
  await startMatch(host)
  await host.evaluate(()=>window.scrollTo(0,0))
  await expect(host.getByRole('button',{name:'Numeral clues'})).toBeInViewport({ratio:1,timeout:2500})
  await expect(host.getByRole('button',{name:'Numeral legend'})).toHaveCount(0)
  await expect(host.getByRole('region',{name:'Magic square grid'}).getByRole('button')).toHaveCount(49)
  const rack=host.getByRole('region',{name:'Tile tray'})
  const tile=rack.getByRole('button',{name:/^Tile /})
  await expect(tile).toHaveCount(48)
  await expect(tile.first()).toBeInViewport({ratio:1})
  await expect(rack.getByRole('button',{name:/value \d+/})).toHaveCount(0)
  const rail=host.getByRole('button',{name:'Next tiles'})
  await rail.tap()
  await expect.poll(()=>rack.evaluate(el=>el.scrollLeft)).toBeGreaterThan(0)
  await host.getByRole('button',{name:'Previous tiles'}).tap()
  await expect.poll(()=>rack.evaluate(el=>el.scrollLeft)).toBe(0)
  await tile.first().tap()
  await expect(host.getByRole('status').filter({hasText:/Selected .* Choose a cell/})).not.toContainText('value')
  const target=host.getByRole('region',{name:'Magic square grid'}).getByRole('button',{name:/empty$/}).first()
  await expect(target).toBeInViewport({ratio:1})
  const address=(await target.getAttribute('aria-label'))!.split(': ')[0]
  await target.tap()
  await expect(host.getByRole('button',{name:address+': empty',exact:true})).toHaveCount(0)
  await expect(guest.getByRole('button',{name:address+': empty',exact:true})).toBeVisible()
  await host.getByRole('button',{name:'Numeral clues'}).tap()
  await expect(host.locator('.divine-key li')).toHaveCount(10)
  expect(await host.evaluate(()=>document.documentElement.scrollWidth)).toBe(320)
 }finally{await hctx.close();await gctx.close()}
})

test('Divine still plays a 5×5 square in solo with the selected time limit',async({page})=>{
 await page.setViewportSize({width:390,height:844})
 await page.goto('./season/3/')
 await page.getByRole('button',{name:'Practice Divine Test',exact:true}).click()
 await page.getByLabel('Square size').selectOption('5')
 await page.getByLabel('Time limit').selectOption('300')
 await startMatch(page)
 await expect(page.getByText('Every line: 65')).toBeVisible()
 await expect(page.getByRole('timer',{name:'Time remaining'})).toHaveText(/^(?:5:00|4:[0-5]\d)$/)
 const board=page.getByRole('region',{name:'Magic square grid'})
 await expect(board.getByRole('button')).toHaveCount(25)
 const tile=page.getByRole('region',{name:'Tile tray'}).getByRole('button').first()
 await tile.click()
 await board.getByRole('button',{name:/empty$/}).first().click()
 await expect(board.getByRole('button',{name:/value/})).toHaveCount(2)
})
