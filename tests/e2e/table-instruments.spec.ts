import {expect,test} from '@playwright/test'

test('party instruments expose the host selection to a read-only phone guest',async({browser,baseURL})=>{
 const hostContext=await browser.newContext({viewport:{width:1280,height:900},reducedMotion:'reduce'})
 const guestContext=await browser.newContext({viewport:{width:320,height:720},hasTouch:true,isMobile:true,reducedMotion:'reduce'})
 try{
  const host=await hostContext.newPage(), guest=await guestContext.newPage()
  await host.goto(baseURL!)
  await host.getByLabel('Nickname').fill('Example Host')
  await host.getByRole('button',{name:'Create party'}).click()
  const code=await host.getByTestId('room-code').textContent()
  await guest.goto(baseURL!+'#/join?room='+code)
  await guest.getByLabel('Nickname').fill('Example Guest')
  await guest.getByRole('button',{name:'Join party'}).tap()
  await expect(guest.getByRole('button',{name:'Ready up'})).toBeVisible()
  const settings=host.getByRole('region',{name:'Table settings'})
  await expect(settings).toBeVisible()
  await expect(settings.getByRole('combobox')).toHaveCount(0)
  await host.getByRole('button',{name:'Choose game',exact:true}).click()
  const shelf=host.getByRole('dialog',{name:'Choose a game'})
  await shelf.getByRole('searchbox').fill('Divine Test')
  await shelf.getByRole('button',{name:/^Divine Test/}).click()
  await expect(settings.getByRole('radiogroup',{name:'Square size'}).getByRole('radio',{name:'7 × 7',exact:true})).toBeChecked()
  const sizes=settings.getByRole('radiogroup',{name:'Square size'})
  await sizes.getByRole('radio',{name:'7 × 7',exact:true}).focus()
  await host.keyboard.press('ArrowLeft')
  await expect(sizes.getByRole('radio',{name:'5 × 5',exact:true})).toBeChecked()
  const guestSize=guest.getByRole('radiogroup',{name:'Square size'}).getByRole('radio',{name:'5 × 5',exact:true})
  await expect(guestSize).toBeChecked()
  await expect(guestSize).toBeDisabled()
  await expect(guest.getByRole('button',{name:'Choose game',exact:true})).toHaveCount(0)
  await expect(guest.getByRole('button',{name:'Increase seat limit'})).toHaveCount(0)
  expect(await guest.evaluate(()=>document.documentElement.scrollWidth)).toBe(320)
  const switcher=settings.getByRole('switch',{name:'Deduce the numeral key'})
  await switcher.click()
  await expect(guest.getByRole('switch',{name:'Deduce the numeral key'})).toBeChecked()
  await expect(guest.getByRole('switch',{name:'Deduce the numeral key'})).toBeDisabled()
  await settings.getByRole('radiogroup',{name:'Time limit'}).getByRole('radio',{name:'5 minutes',exact:true}).click()
  await expect(guest.getByRole('radiogroup',{name:'Time limit'}).getByRole('radio',{name:'5 minutes',exact:true})).toBeChecked()
  await host.getByRole('button',{name:'Choose game',exact:true}).click()
  await shelf.getByRole('searchbox').fill('Heavy 13')
  await shelf.getByRole('button',{name:/^Heavy 13/}).click()
  const up=settings.getByRole('button',{name:'Increase seat limit'})
  const down=settings.getByRole('button',{name:'Decrease seat limit'})
  await expect(up).toBeDisabled()
  for(let n=7;n>2;n--)await down.click()
  await expect(down).toBeDisabled()
  await expect(host.getByRole('button',{name:'Add bot'})).toBeDisabled()
  await up.click()
  await host.getByRole('button',{name:'Add bot'}).click()
  await expect(down).toBeDisabled()
  await expect(guest.locator('.instrument-seat-marks [data-mark=bot]')).toHaveCount(1)
 }finally{await Promise.all([hostContext.close(),guestContext.close()])}
})

test('320px practice uses the game shelf and graphical controls without a native dropdown',async({browser})=>{
 const context=await browser.newContext({viewport:{width:320,height:720},hasTouch:true,isMobile:true,reducedMotion:'reduce'})
 try{
  const page=await context.newPage()
  page.setDefaultTimeout(7000)
  await page.goto('./season/2/')
  await page.getByRole('button',{name:'Practice Knight’s Tour',exact:true}).tap()
  const settings=page.getByRole('region',{name:'Table settings'})
  await expect(settings.getByRole('combobox')).toHaveCount(0)
  const options=settings.getByRole('radiogroup',{name:'Board size'})
  const six=options.getByRole('radio',{name:'6 × 6',exact:true})
  await expect(six.locator('svg')).toBeVisible()
  expect((await six.boundingBox())!.height).toBeGreaterThanOrEqual(44)
  await six.tap()
  await expect(six).toBeChecked()
  const closed=settings.getByRole('switch',{name:'Closed tour'})
  await closed.tap()
  await expect(closed).toBeChecked()
  await page.getByRole('button',{name:'Choose game',exact:true}).tap()
  const shelf=page.getByRole('dialog',{name:'Choose a game'})
  await shelf.getByRole('searchbox').fill('Time Auction')
  await shelf.getByRole('button',{name:/^Time Auction/}).tap()
  await expect(settings.getByRole('radiogroup',{name:'Board size'})).toHaveCount(0)
  await expect(settings.getByRole('radiogroup',{name:'Time Auction mode'})).toHaveCount(0)
  await expect(settings.getByRole('radiogroup',{name:'Seconds to submit'}).getByRole('radio',{name:'90 seconds',exact:true})).toBeChecked()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(320)
  await page.getByRole('button',{name:'Choose game',exact:true}).tap()
  await shelf.getByRole('searchbox').fill('Secret Code')
  await shelf.getByRole('button',{name:/^Secret Code/}).tap()
  await expect(settings).toHaveCount(0)
 }finally{await context.close()}
})
