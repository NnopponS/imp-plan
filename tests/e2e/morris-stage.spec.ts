import {expect,test,type Page} from '@playwright/test'
import {chooseGame} from '../lobby-controls'
import {startMatch} from './start-match'

const table=(page:Page)=>page.getByRole('region',{name:'Nine Men’s Morris table'})
const point=(page:Page,n:number,fill='open')=>table(page).getByRole('button',{name:'Point '+n+', '+fill,exact:true})

test('the live wooden table fits phone touch play and records accepted stones',async({browser})=>{
 const context=await browser.newContext({viewport:{width:320,height:568},hasTouch:true,isMobile:true,reducedMotion:'reduce'})
 try{
  const page=await context.newPage()
  await page.goto('./season/1/')
  await page.getByRole('button',{name:'Practice Nine Men’s Morris',exact:true}).tap()
  await startMatch(page)
  await expect(table(page).locator('[data-morris-board]')).toBeInViewport({ratio:1})
  await expect(table(page).locator('button[data-morris-point]')).toHaveCount(24)
  await expect(table(page).getByRole('status')).toContainText('Place a stone')
  const open=point(page,1)
  const sizes=await table(page).locator('button[data-morris-point]').evaluateAll(nodes=>nodes.map(point=>{
   const {width,height}=point.getBoundingClientRect()
   return [width,height]
  }))
  expect(sizes.every(([width,height])=>width>=44&&height>=44)).toBe(true)
  const art=table(page).locator('img.morris-chamber-art')
  await expect(art).toHaveAttribute('src',/morris-live-chamber\.webp$/)
  await expect.poll(()=>art.evaluate((image:HTMLImageElement)=>image.complete&&image.naturalWidth>0)).toBe(true)
  const ghosts=table(page).locator('[data-morris-ghost]:visible')
  await expect(ghosts).toHaveCount(0)
  const touch=await context.newCDPSession(page)
  const area=(await open.boundingBox())!
  await touch.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:area.x+area.width/2,y:area.y+area.height/2}]})
  await expect(open.locator('[data-morris-ghost]')).toBeVisible()
  await expect(ghosts).toHaveCount(1)
  if(process.env.MORRIS_DRAWN_PROOF)await page.screenshot({path:process.env.MORRIS_DRAWN_PROOF+'/morris-320-touch-ghost.png'})
  await touch.send('Input.dispatchTouchEvent',{type:'touchCancel',touchPoints:[]})
  await expect(ghosts).toHaveCount(0)
  await expect(open.locator('[data-morris-stone]')).toHaveCount(0)
  await open.tap()
  const accepted=point(page,1,'Player')
  await expect(accepted.locator('[data-morris-stone]')).toHaveCount(1)
  await expect(accepted.locator('svg[data-morris-stone]')).toBeVisible()
  expect(await accepted.locator('[data-morris-stone]').evaluate(node=>node.getAnimations().length)).toBe(0)
  await expect(table(page).getByLabel('Player, 1 stone on board')).toBeVisible()
  if(process.env.MORRIS_DRAWN_PROOF)await page.screenshot({path:process.env.MORRIS_DRAWN_PROOF+'/morris-320-placed.png'})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(320)
 }finally{await context.close()}
})

test('two seats form a mill, capture, and slide only to a legal point',async({browser,baseURL})=>{
 const h=await browser.newContext({viewport:{width:1440,height:900}})
 const g=await browser.newContext({viewport:{width:390,height:844},hasTouch:true,isMobile:true})
 try{
  const host=await h.newPage(),guest=await g.newPage()
  await host.goto('./season/1/')
  await host.getByLabel('Nickname').fill('Amber')
  await host.getByRole('button',{name:'Create party'}).click()
  const room=host.getByTestId('room-code')
  await expect(room).toHaveText(/^[A-Z2-9]{6}$/)
  await guest.goto(baseURL!+'#/join?room='+await room.textContent())
  await guest.getByLabel('Nickname').fill('Ivory')
  await guest.getByRole('button',{name:'Join party'}).tap()
  await chooseGame(host,'morris')
  await guest.getByRole('button',{name:'Ready up'}).tap()
  await expect(host.getByRole('button',{name:'Start match',exact:true})).toBeEnabled()
  await startMatch(host)
  await expect(table(host)).toBeVisible()
  await expect(table(guest)).toBeVisible()
  await expect(point(guest,1)).toHaveAttribute('aria-disabled','true')
  await point(guest,1).focus()
  await expect(table(guest).locator('[data-morris-ghost]:visible')).toHaveCount(0)
  await point(host,1).hover()
  await expect(point(host,1).locator('[data-morris-ghost]')).toBeVisible()
  await expect(table(host).locator('[data-morris-ghost]:visible')).toHaveCount(1)
  await table(host).locator('.morris-cue').hover()
  await point(host,1).focus()
  await host.keyboard.press('ArrowRight')
  await expect(point(host,2)).toBeFocused()
  await expect(point(host,2).locator('[data-morris-ghost]')).toBeVisible()
  await host.keyboard.press('ArrowLeft')
  await host.keyboard.press('Enter')
  await expect(point(guest,1,'Amber')).toBeVisible()
  await expect(point(guest,4)).toHaveAttribute('aria-disabled','false')
  await point(guest,4).tap()
  await expect(point(host,2)).toHaveAttribute('aria-disabled','false')
  await point(host,2).press('Enter')
  await expect(point(guest,7)).toHaveAttribute('aria-disabled','false')
  await point(guest,7).tap()
  await expect(point(host,3)).toHaveAttribute('aria-disabled','false')
  await point(host,3).press('Enter')
  await expect(table(host).getByRole('status')).toContainText('Remove a stone')
  await expect(table(host).locator('[data-morris-mill]')).toHaveCount(1)
  await expect(table(host).locator('[data-phase-mark=capture]')).toBeVisible()
  await expect(table(host).locator('[data-morris-ghost]:visible')).toHaveCount(0)
  if(process.env.MORRIS_DRAWN_PROOF)await table(host).screenshot({path:process.env.MORRIS_DRAWN_PROOF+'/morris-1440-mill.png'})
  await expect(point(host,4,'Ivory')).toHaveAttribute('aria-disabled','false')
  await expect(point(host,5)).toHaveAttribute('aria-disabled','true')
  await point(host,4,'Ivory').press('Enter')
  await expect(point(guest,4)).toBeVisible()
  await expect(table(guest).getByLabel('Ivory, 1 stone on board')).toBeVisible()
  await expect(table(guest).getByRole('status')).toContainText('Place a stone')

  // Finish deployment without forming another mill, then exercise the actual slide.
  for(const [i,n] of [4,5,6,9,8,10,11,12,13,14,15,16,17].entries()){
   const turn=i%2===0?guest:host
   const destination=point(turn,n)
   await expect(destination).toHaveAttribute('aria-disabled','false')
   await destination.press('Enter')
  }
  await expect(table(host).getByRole('status')).toContainText('Choose a stone')
  const source=point(host,10,'Amber')
  await source.press('Enter')
  await expect(source).toHaveAttribute('aria-pressed','true')
  await expect(point(host,22)).toHaveAttribute('aria-disabled','false')
  await expect(point(host,23)).toHaveAttribute('aria-disabled','true')
  await point(host,22).hover()
  await expect(point(host,22).locator('[data-morris-ghost]')).toBeVisible()
  if(process.env.MORRIS_DRAWN_PROOF)await table(host).screenshot({path:process.env.MORRIS_DRAWN_PROOF+'/morris-1440-slide-ghost.png'})
  await point(host,23).hover()
  await expect(point(host,23).locator('[data-morris-ghost]')).toHaveCount(0)
  await point(host,23).press('Enter')
  await expect(point(host,23).locator('[data-morris-stone]')).toHaveCount(0)
  await source.press('Escape')
  await expect(source).toHaveAttribute('aria-pressed','false')
  await source.press('Enter')
  await point(host,22).press('Enter')
  await expect(point(guest,22,'Amber')).toBeVisible()
  await expect(point(host,22,'Amber').locator('[data-enter=true]')).toHaveCount(1)
  await expect(point(host,10).locator('[data-morris-stone]')).toHaveCount(0)
 }finally{await Promise.all([h.close(),g.close()])}
})

test('the same table stays above the fold on a short landscape screen',async({page})=>{
 await page.setViewportSize({width:844,height:390})
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.goto('./season/1/')
 await page.getByRole('button',{name:'Practice Nine Men’s Morris',exact:true}).click()
 await startMatch(page)
 if(process.env.MORRIS_DRAWN_PROOF)await page.screenshot({path:process.env.MORRIS_DRAWN_PROOF+'/morris-844-place.png'})
 await expect(table(page).locator('[data-morris-board]')).toBeInViewport({ratio:.9})
 await expect(table(page).getByRole('status')).toBeInViewport()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(844)
})
