import {expect,test} from '@playwright/test'
import {startMatch} from './start-match'
import {chooseGame,chooseSetting} from '../lobby-controls'

const cases=[['Balance Mancala','mancala','.mancala-pit',9],['Blind Gomoku','blind','.chamber-grid button.cell',225],['Big Small','bigSmall','[data-bs-card]',11]] as const
for(const [title,key,selector,count] of cases) test(title+' previews its real opening artwork without entering a match',async({page})=>{
 await page.setViewportSize({width:390,height:844})
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.goto('./')
 await page.locator('#play input[type=search]').fill(title)
 await page.getByRole('button',{name:'Open '+title,exact:true}).click()
 const details=page.getByRole('dialog',{name:title,exact:true})
 const sample=details.locator('[data-real-table-preview="'+key+'"]')
 await expect(sample.locator(selector)).toHaveCount(count)
 await expect(sample.locator(selector).first()).toBeVisible()
 await expect(sample.locator('[inert]')).toHaveCount(1)
 await expect(details.locator('[data-game-preview]')).toHaveCount(0)
 await expect(details.getByText('Illustrated rules',{exact:true})).toBeVisible()
 await details.getByRole('button',{name:'Practice '+title,exact:true}).click()
 await startMatch(page)
 const live=page.locator('.room[data-game="'+key+'"]')
 await expect(live.locator(selector)).toHaveCount(count)
 await expect(page.locator('.room [inert]')).toHaveCount(0)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(390)
})

test('a current table preview mirrors each selected episode variant without starting the match',async({browser,baseURL})=>{
 const contexts=await Promise.all([browser.newContext(),browser.newContext({hasTouch:true,viewport:{width:390,height:844}})])
 try{
  const [host,guest]=await Promise.all(contexts.map(c=>c.newPage()))
  await host.goto(baseURL!);await host.getByLabel('Nickname').fill('Preview host')
  await host.getByRole('button',{name:'Create party',exact:true}).click()
  const code=await host.getByTestId('room-code').textContent()
  await guest.goto(baseURL!+'#/join?room='+code);await guest.getByLabel('Nickname').fill('Preview guest')
  await guest.getByRole('button',{name:'Join party',exact:true}).tap()
  const trigger=guest.getByRole('button',{name:'Preview the table',exact:true})
  await expect(trigger).toBeVisible()
  await chooseGame(host,'auction')
  await chooseSetting(host,'Time Auction mode','hold')
  const current=guest.getByRole('region',{name:'Current table'})
  await expect(current).toContainText('Hold & release')
  await trigger.tap()
  const hold=guest.getByRole('dialog',{name:'Time Auction',exact:true})
  const fixture=hold.locator('[data-real-table-preview="auction"][data-sample-variant="hold"]')
  await expect(fixture.locator('.time-hold')).toBeVisible()
  await expect(fixture.locator('button[aria-label="Hold to bid"]')).toBeVisible()
  await expect(fixture.locator('[inert]')).toHaveCount(1)
  await expect(guest.locator('.room[data-live-match]:not([data-sample-table])')).toHaveCount(0)
  await hold.getByRole('button',{name:'Close details',exact:true}).tap()
  await expect(trigger).toBeFocused()
  await chooseGame(host,'memoryPoker')
  await chooseSetting(host,'Memory Poker mode','episode')
  await expect(current).toContainText('Episode-style duel')
  await trigger.tap()
  const duel=guest.locator('[data-real-table-preview="memoryPoker"][data-sample-variant="episode"]')
  await expect(duel.locator('.memory-card')).toHaveCount(16)
  await expect(guest.locator('.room[data-live-match]:not([data-sample-table])')).toHaveCount(0)
 }finally{await Promise.all(contexts.map(c=>c.close()))}
})
