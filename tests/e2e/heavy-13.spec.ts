import {expect,test} from '@playwright/test'
import {startMatch} from './start-match'

test('private Heavy 13 keeps picks hidden, reverses a pass, counts old zero cubes, and continues across rounds',async({browser,baseURL})=>{
 const desk=await browser.newContext(),phone=await browser.newContext({viewport:{width:360,height:780},hasTouch:true})
 try{
  const host=await desk.newPage(),guest=await phone.newPage()
  await host.goto(baseURL!+'season/3/')
  await host.getByRole('button',{name:'Practice Heavy 13'}).scrollIntoViewIfNeeded()
  const card=host.getByRole('article').filter({has:host.getByRole('heading',{name:'Heavy 13',exact:true})}).first()
  await expect.poll(()=>card.locator('img').evaluate((n:HTMLImageElement)=>n.complete&&n.naturalWidth>0)).toBe(true)
  await host.getByLabel('Nickname').fill('Ada')
  await host.getByRole('button',{name:'Create party'}).click()
  const code=(await host.getByTestId('room-code').textContent())!
  await host.getByRole('combobox',{name:'Game',exact:true}).selectOption('heavy13')
  await host.getByRole('combobox',{name:'Seconds per selection or placement'}).selectOption('45')
  await guest.goto(baseURL!+'#/join?room='+code)
  await guest.getByLabel('Nickname').fill('Mina')
  await guest.getByRole('button',{name:'Join party'}).click()
  await guest.getByRole('button',{name:'Preview rules'}).click()
  await expect(guest.getByRole('dialog').getByRole('img',{name:'Heavy 13 scoring example'})).toBeVisible()
  await guest.getByRole('button',{name:'Back to lobby'}).click()
  await guest.getByRole('button',{name:'Ready up'}).click()
  await startMatch(host)
  const board=(p:typeof host)=>p.getByRole('region',{name:'Heavy 13 table'})
  const button=(p:typeof host,name:string)=>board(p).getByRole('button',{name,exact:true})
  const status=(p:typeof host)=>board(p).getByRole('status')
  const red=(p:typeof host)=>board(p).getByRole('group',{name:'Red stand',exact:true})
  await expect(board(host).getByRole('timer')).toBeVisible()
  await button(host,'Number 6').focus()
  await button(host,'Number 6').press('Enter')
  await button(host,'Red, 2 left').press('Space')
  await button(host,'Lock pair privately').press('Enter')
  await expect(status(host)).toContainText('Locked privately')
  await expect(status(guest)).toContainText('Choose one number and one color')
  await expect(board(guest).getByRole('list',{name:'Placement order'})).toHaveCount(0)
  await button(guest,'Number 0').tap()
  await button(guest,'Rainbow, 1 left').tap()
  await button(guest,'Lock pair privately').tap()
  await expect(status(guest)).toContainText('Your call')
  await expect(button(host,'Place on Red')).toHaveCount(0)
  await button(guest,'Pass once').tap()
  await expect(status(host)).toContainText('Your call')
  await expect(button(host,'Pass once')).toBeDisabled()
  await button(host,'Place on Red').press('Enter')
  await expect(status(guest)).toContainText('return')
  await button(guest,'Place on Red').tap()
  await expect(board(host).getByText('Round 2 / 14',{exact:true})).toBeVisible()
  await expect(red(host).getByText('6 / 13',{exact:true})).toBeVisible()
  await button(host,'Number 5').press('Enter')
  await button(host,'Red, 1 left').press('Enter')
  await button(host,'Lock pair privately').press('Enter')
  await button(guest,'Number 6').tap()
  await button(guest,'Red, 2 left').tap()
  await button(guest,'Lock pair privately').tap()
  await button(guest,'Place on Red').tap()
  await expect(red(host).getByText('12 / 13',{exact:true})).toBeVisible()
  await button(host,'Place on Red').press('Enter')
  await expect(board(guest).getByText('Round 3 / 14',{exact:true})).toBeVisible()
  await expect(board(guest).getByText('Ada took 3 penalty cubes (6, 0, 6).')).toBeVisible()
  await expect(red(guest).getByText('5 / 13',{exact:true})).toBeVisible()
  expect(await guest.evaluate(()=>document.documentElement.scrollWidth)).toBe(360)
 }finally{await Promise.allSettled([desk.close(),phone.close()])}
})

test('Heavy 13 solo starts with one bot, accepts keyboard choices, and reaches the next round at 390px',async({page,baseURL})=>{
 await page.setViewportSize({width:390,height:844})
 await page.goto(baseURL!+'season/3/')
 await page.getByLabel('Nickname').fill('Ada')
 await page.getByRole('button',{name:'Practice Heavy 13'}).click()
 await page.getByRole('combobox',{name:/Bot difficulty/}).selectOption('hard')
 await startMatch(page)
 const board=page.getByRole('region',{name:'Heavy 13 table'})
 await expect(board.getByText('Bot 1',{exact:true})).toBeVisible()
 for(const name of ['Number 6','Rainbow, 1 left','Lock pair privately'])await board.getByRole('button',{name,exact:true}).press('Enter')
 await board.getByRole('button',{name:'Place on Green',exact:true}).press('Enter')
 await expect(board.getByText('Round 2 / 14',{exact:true})).toBeVisible()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(390)
})
