import {expect,test} from '@playwright/test'

test('Tab enters the board once and arrows move between open squares',async({page})=>{
 await page.setViewportSize({width:320,height:690})
 await page.goto('./')
 const board=page.getByRole('region',{name:'One-move warm-up'})
 const first=board.getByRole('button',{name:'Row 6, column 4, empty'})
 await first.focus()
 await page.keyboard.press('ArrowRight')
 await expect(board.getByRole('button',{name:'Row 6, column 5, empty'})).toBeFocused({timeout:3000})
 await page.keyboard.press('ArrowDown')
 await expect(board.getByRole('button',{name:'Row 9, column 5, empty'})).toBeFocused()
 await page.keyboard.press('Tab')
 await expect(board.getByRole('button',{name:'Full Blind Gomoku'})).toBeFocused()
 await page.keyboard.press('Shift+Tab')
 await expect(board.getByRole('button',{name:'Row 9, column 5, empty'})).toBeFocused()
})

test('the skip shortcut leaves the board without making a move',async({page})=>{
 await page.goto('./')
 const board=page.getByRole('region',{name:'One-move warm-up'})
 const skip=board.getByRole('link',{name:'Skip warm-up',exact:true})
 await skip.focus({timeout:3000})
 await page.keyboard.press('Enter')
 await expect(board.getByRole('button',{name:'Full Blind Gomoku'})).toBeFocused()
 await expect(board.getByRole('status')).toHaveText('Find the fifth stone in the row.')
})

test('keyboard play reports a win and Reset returns focus to the board',async({page})=>{
 await page.goto('./')
 const board=page.getByRole('region',{name:'One-move warm-up'})
 const reset=board.getByRole('button',{name:'Reset warm-up'})
 const first=board.getByRole('button',{name:'Row 6, column 4, empty'})
 await first.focus()
 for(let i=0;i<5;i++)await page.keyboard.press('ArrowRight')
 await page.keyboard.press('ArrowDown')
 await page.keyboard.press('ArrowDown')
 await expect(board.getByRole('button',{name:'Row 8, column 9, empty'})).toBeFocused({timeout:3000})
 await page.keyboard.press('Space')
 await expect(board.getByRole('status')).toHaveText('Five in a row. You win!')
 await expect(reset).toBeFocused()
 await page.keyboard.press('Enter')
 await expect(board.getByRole('status')).toHaveText('Find the fifth stone in the row.')
 await expect(first).toBeFocused()
})
