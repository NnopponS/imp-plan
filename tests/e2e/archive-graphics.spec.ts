import {expect,test} from '@playwright/test'
import {selectedGame} from '../lobby-controls'

test('chapter bookmarks keep a 44px tap target and navigate to the selected season',async({page})=>{
 await page.setViewportSize({width:320,height:640})
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.goto('./')
 const tab=page.getByRole('navigation',{name:'Seasons'}).getByRole('link',{name:'Season 2',exact:true})
 const box=await tab.boundingBox()
 expect(box?.height).toBeGreaterThanOrEqual(44)
 await tab.focus()
 await page.keyboard.press('Enter')
 await expect(tab).toHaveAttribute('aria-current','page')
 await expect(page.getByRole('button',{name:'Practice Time Auction',exact:true})).toBeInViewport({ratio:1})
})

test('archive switches shelf and chapter without losing the search',async({page})=>{
 await page.goto('./#play')
 await page.getByRole('link',{name:'Challenge index',exact:true}).click()
 const index=page.locator('#catalog')
 const search=index.getByLabel('Search challenge index')
 const archived=index.getByRole('button',{name:'Archive only',exact:true})
 const playable=index.getByRole('button',{name:'Playable only',exact:true})
 await expect(archived).toBeVisible({timeout:900})
 await search.fill('Poker')
 await archived.focus()
 await page.keyboard.press('Space')
 await expect(archived).toHaveAttribute('aria-pressed','true')
 await expect(index.getByText('Dice Poker',{exact:true})).toBeVisible()
 await expect(index.locator('strong').getByText('Memory Poker',{exact:true})).toHaveCount(0)
 await expect(search).toHaveValue('Poker')
 await playable.click()
 await expect(index.getByText('Dice Poker',{exact:true})).toHaveCount(0)
 const season=index.getByRole('button',{name:'Season 3',exact:true})
 await season.click()
 await expect(season).toHaveAttribute('aria-pressed','true')
 await expect(index.locator('strong').getByText('Memory Poker',{exact:true})).toBeVisible()
 await index.getByRole('button',{name:'Practice Memory Poker',exact:true}).click()
 await expect(selectedGame(page,'memoryPoker')).toBeVisible()
 await page.getByRole('button',{name:'Leave room',exact:true}).click()
 await expect(search).toHaveValue('Poker')
 await expect(index.getByRole('button',{name:'Practice Memory Poker',exact:true})).toBeFocused()
})

test('venue seals filter in place, can clear, and do not crowd 320px',async({page})=>{
 await page.setViewportSize({width:320,height:640})
 await page.goto('./season/3/#play')
 await page.getByRole('link',{name:'Challenge index',exact:true}).click()
 const index=page.locator('#catalog')
 await index.getByText('Filter by venue',{exact:true}).click()
 const exile=index.getByRole('button',{name:'Exile',exact:true})
 await expect(exile).toBeVisible({timeout:900})
 await exile.click()
 await expect(exile).toHaveAttribute('aria-pressed','true')
 await expect(index.locator('strong').getByText('Point Gomoku',{exact:true})).toBeVisible()
 await expect(index.locator('strong').getByText('Memory Poker',{exact:true})).toHaveCount(0)
 await exile.click()
 await expect(exile).toHaveAttribute('aria-pressed','false')
 await expect(index.locator('strong').getByText('Memory Poker',{exact:true})).toBeVisible()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(320)
})
