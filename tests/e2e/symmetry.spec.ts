import {expect,test,type Page} from '@playwright/test'
import {startMatch} from './start-match'
import {chooseGame,tableRadio} from '../lobby-controls'

const table=(page:Page)=>page.getByRole('region',{name:'Symmetrical Puzzle board',exact:true})
const piece=(page:Page)=>table(page).getByRole('button',{name:/^Moth, \d+ cells, in tray$/})
const anchor=(page:Page)=>table(page).locator('button[data-spot="0"]')
const placed=(page:Page,count:number)=>table(page).getByLabel(new RegExp('^'+count+' of [0-9]+ pieces placed$'))
const startConfig=async(page:Page)=>{await tableRadio(page,'Mirror axis','Diagonal').click();await expect(tableRadio(page,'Mirror axis','Diagonal')).toBeChecked()}

test('320px solo practice places and lifts by keyboard, keeps the board in focus and rematches after time',async({browser,baseURL})=>{
 const phone=await browser.newContext({viewport:{width:320,height:730},hasTouch:true,isMobile:true,reducedMotion:'reduce'})
 try{
  const page=await phone.newPage()
  await page.clock.install()
  await page.goto(baseURL!+'season/3/')
  await page.getByRole('button',{name:'Practice Symmetrical Puzzle',exact:true}).tap()
  await startConfig(page)
  await startMatch(page)
  await expect(table(page)).toBeVisible()
  const rail=page.getByRole('region',{name:'At this table',exact:true})
  await expect(rail.getByText('Player',{exact:true})).toBeVisible()
  await expect(rail.getByRole('group',{name:'Opponents'})).toHaveCount(0)
  const before=await anchor(page).getAttribute('aria-label')
  expect(before).toMatch(/Row 1, column 1, empty/)
  await piece(page).press('Enter')
  await anchor(page).press('Enter')
  await expect(placed(page,1)).toBeAttached()
  await page.getByRole('button',{name:'Board focus',exact:true}).tap()
  await expect(rail).not.toBeVisible()
  await expect(table(page).getByRole('button',{name:/^Moth, [0-9]+ cells, on board$/})).toBeVisible()
  await page.getByRole('button',{name:'Exit focus',exact:true}).tap()
  await expect(table(page).getByRole('button',{name:/^Moth, [0-9]+ cells, on board$/})).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(320)
  await table(page).getByRole("button",{name:/^Moth, [0-9]+ cells, on board$/}).press("Enter")
  await table(page).getByRole("button",{name:"Lift",exact:true}).press("Enter")
  await expect(placed(page,0)).toBeAttached()
  await page.clock.fastForward(241000)
  const record=page.getByRole('region',{name:'Match record',exact:true})
  await expect(record).toContainText('Time expired')
  await record.getByRole('button',{name:'Rematch',exact:true}).tap()
  await expect(piece(page)).toBeEnabled()
  await expect(placed(page,0)).toBeAttached()
 }finally{await phone.close()}
})

test('a desktop host and phone guest play the same tray but never receive each other’s placements',async({browser,baseURL})=>{
 const desk=await browser.newContext({viewport:{width:1280,height:820},reducedMotion:'reduce'})
 const phone=await browser.newContext({hasTouch:true,viewport:{width:844,height:390},reducedMotion:'reduce'})
 try{
  const host=await desk.newPage(),guest=await phone.newPage()
  await host.goto(baseURL!)
  await host.getByLabel('Nickname').fill('Bench host')
  await host.getByRole('button',{name:'Create party'}).click()
  const code=(await host.getByTestId('room-code').textContent())!
  await chooseGame(host,'symmetry')
  await startConfig(host)
  await guest.goto(baseURL!+'#/join?room='+code)
  await guest.getByLabel('Nickname').fill('Mirror guest')
  await guest.getByRole('button',{name:'Join party'}).click()
  await guest.getByRole('button',{name:'Ready up',exact:true}).tap()
  await startMatch(host)
  await expect(table(guest)).toBeVisible()
  expect(await piece(host).getAttribute('aria-label')).toBe(await piece(guest).getAttribute('aria-label'))
  await piece(host).click()
  await anchor(host).click()
  await expect(placed(host,1)).toBeAttached()
  await expect(anchor(guest)).toHaveAttribute('aria-label',/empty/)
  await expect(placed(guest,0)).toBeAttached()
  await piece(guest).tap()
  await anchor(guest).tap()
  await expect(placed(guest,1)).toBeAttached()
  expect(await guest.evaluate(()=>document.documentElement.scrollWidth)).toBe(844)
 }finally{await desk.close();await phone.close()}
})

test('the painted cover rotates the real piece and lights its mirror seam on a loop',async({page,baseURL})=>{
 await page.setViewportSize({width:390,height:780})
 await page.goto(baseURL!+'season/3/',{waitUntil:'domcontentloaded'})
 const cover=page.locator('[data-preview-game="symmetry"]')
 await cover.evaluate(node=>node.scrollIntoView({block:'center',behavior:'instant'}))
 const moving=cover.locator('img[data-cover-motion]')
 await expect(moving).toHaveAttribute('data-cover-ready','true')
 await expect(moving).toHaveAttribute('data-cover-original',/seasonal-symmetry\.svg$/)
 const cues=await moving.evaluate(async (image:HTMLImageElement)=>{
  const doc=new DOMParser().parseFromString(await (await fetch(image.src)).text(),'image/svg+xml')
  return Array.from(doc.querySelectorAll('[data-cover-at]')).map(n=>({attribute:n.getAttribute('attributeName'),kind:n.getAttribute('type'),loop:n.getAttribute('repeatCount')}))
 })
 expect(cues).toContainEqual({attribute:'transform',kind:'rotate',loop:'indefinite'})
 expect(cues.filter(c=>c.attribute==='opacity'&&c.loop==='indefinite')).toHaveLength(3)
 await page.getByRole('button',{name:'Pause previews'}).click()
 await expect(moving).toHaveCount(0)
 await expect(cover.locator('img[data-arena-art]')).toBeAttached()
})
