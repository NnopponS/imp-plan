import {createHash} from 'node:crypto'
import {readFileSync,readdirSync,writeFileSync} from 'node:fs'

const dist=new URL('../dist/',import.meta.url)
const sha256=(bytes,encoding)=>createHash('sha256').update(bytes).digest(encoding)
const pages=['index.html',...[1,2,3].map(n=>'season/'+n+'/index.html')]
function files(dir){
 return readdirSync(new URL(dir+'/',dist),{withFileTypes:true}).flatMap(item=>{
  const path=dir+'/'+item.name
  if(item.isDirectory())return files(path)
  if(!item.isFile())throw new Error('Unexpected non-file in offline assets: '+path)
  return [path]
 })
}
// The document release ID covers both the unmarked HTML and every static asset,
// not just the entry filename. Omit an existing tag so postbuild is idempotent.
const releaseTag=/<meta name="imp-plan-release" content="[0-9a-f]{64}">\n?/
const markup=new Map(pages.map(path=>[path,readFileSync(new URL(path,dist),'utf8').replace(releaseTag,'')]))
const integrity=bytes=>'sha256-'+sha256(bytes,'base64')
const manifest=new Map([...pages,...files('assets'),...files('art')].sort().map(path=>
 [path,integrity(markup.get(path)??readFileSync(new URL(path,dist)))]
))
const release=sha256(JSON.stringify([...manifest]),'hex')
for(const [path,html] of markup){
 const head=html.indexOf('</head>')
 if(head<0)throw new Error('No head in offline document: '+path)
 const marked=html.slice(0,head)+`<meta name="imp-plan-release" content="${release}">\n`+html.slice(head)
 writeFileSync(new URL(path,dist),marked)
 manifest.set(path,integrity(marked))
}
const assets=[...manifest]
const worker=readFileSync(new URL('offline-worker.js',import.meta.url),'utf8')
const version=sha256(JSON.stringify({pages,assets,worker}),'hex')
writeFileSync(new URL('sw.js',dist),`/* Generated by scripts/build-offline.mjs; do not edit. */
const VERSION=${JSON.stringify(version)}
const RELEASE=${JSON.stringify(release)}
const PAGES=${JSON.stringify(pages)}
const ASSETS=${JSON.stringify(assets)}
${worker}`)
